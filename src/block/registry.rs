//! 方块属性注册表：把 PocketMine 的方块类属性编译为静态表。
//!
//! 每个 ID 对应一个 `BlockInfo`，保存名称、硬度、发光、固/透明判定、
//! 光照衰减、摩擦、工具、可激活/可替换/可流过等属性，以及按 meta 变化的名称表。
//! 数据由工具从 PocketMine 0.14 方块类自动提取，覆盖 180 个具名方块。

#[allow(unused_imports)]
use super::id;

/// 工具类型，对齐 `pocketmine\item\Tool::TYPE_*`。
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ToolType {
    None, Pickaxe, Axe, Shovel, Shears,
}

/// 单个方块的静态属性（对齐 PocketMine 方块类实例方法）。
#[derive(Clone, Copy, Debug)]
pub struct BlockInfo {
    pub id: u8,
    /// 默认名称（meta=0 或无变体名称表时）
    pub name: &'static str,
    /// 按 meta 变化的名称表；(name, mask) 为 None 时使用 `name`
    pub name_map: Option<&'static [&'static str]>,
    pub name_mask: u8,
    /// 硬度；负数表示不可破坏（如基岩），100 表示液体
    pub hardness: f32,
    /// 发光等级 0..=15
    pub light: u8,
    pub solid: bool,
    pub transparent: bool,
    /// 光穿过该方块后的衰减（0..15，见 `Block::$lightFilter`）
    pub light_filter: u8,
    pub friction: f32,
    pub tool: ToolType,
    pub burn_chance: u8,
    pub burn_ability: u8,
    pub can_be_activated: bool,
    pub can_be_replaced: bool,
    pub can_be_flowed_into: bool,
    pub has_collision: bool,
}

impl BlockInfo {
    /// 取给定 meta 下的显示名称。
    pub fn display_name(&self, meta: u8) -> &'static str {
        if let Some(map) = self.name_map {
            let key = (meta & self.name_mask) as usize;
            if let Some(n) = map.get(key) {
                if !n.is_empty() {
                    return n;
                }
            }
        }
        self.name
    }
}

